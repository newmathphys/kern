#!/usr/bin/env python3
"""Жёсткий гейт на свидетельства: ни один опубликованный лог не должен
заканчиваться ненулевым кодом возврата.

ЗАЧЕМ. Каталог `docs/evidence/` — это то, что аудитор открывает первым. Если
там лежит лог с `RC=1`, значит проект публикует провал рядом с заявлением об
успехе. Ровно так и было: 8 логов оказались снимком ПРОМЕЖУТОЧНОГО состояния
(во время пробы canfail и в грязном дереве).

ПОЧЕМУ НЕ ПРОСТО grep. Наивный `grep -rn "RC=1|FAIL|ОШИБКА"` даёт ложные
срабатывания: в `canfail.log` строки `[FAIL]` — это НАМЕРЕННЫЕ негативные пробы
(харнесс обязан покраснеть), а в логах атак слово `error` встречается как
ожидаемый вывод ядра. Поэтому гейт смотрит на ФИНАЛЬНУЮ строку `RC=<n>`
каждого лога — она пишется сборщиком последней и отражает вердикт целиком.

ИНВАРИАНТ ОДНОГО ПРОГОНА (дефект #81). Лог сборщика обязан содержать РОВНО один
заголовок, одну дату и одну строку `RC=`. Если в файл писали два процесса, внутри
окажутся два заголовка и результаты двух прогонов — тогда «финальный RC»
относится не к тем данным. Именно такой файл наблюдался у `slsa_check.log`.
Логи БЕЗ заголовка считаются снятыми вручную: для них требуется ровно одна
строка `RC=`, и они перечисляются отдельной строкой отчёта.

ИСКЛЮЧЕНИЕ. `canfail.log` — единственный лог, где ненулевые коды ВНУТРИ
являются частью доказательства. Для него проверяется, что итоговая строка
содержит «ВАКУУМНЫХ 0», то есть ни одна проверка не оказалась вакуумной.

Запуск:  python3 tools/evidence_gate.py
Код возврата: 0 — все свидетельства чистые, 1 — найдены нарушения.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EV = ROOT / "docs" / "evidence"

# Логи, внутри которых ненулевые коды — часть доказательства.
# Для них проверяется СМЫСЛОВОЙ инвариант, а не код возврата файла.
INTENTIONAL = {
    "canfail.log": (r"ВАКУУМНЫХ\s+(\d+)", 0,
                    "число вакуумных проверок должно быть 0"),
}

# 🔴 ДЕФЕКТ #77: второй эшелон проверки.
#
# Гейт первого эшелона смотрит только на финальную строку `RC=<n>`. Этого
# недостаточно: лог может заканчиваться `RC=0`, но СОДЕРЖАТЬ провал — именно
# так `docs/evidence/slsa_check.log` нёс «АТТЕСТАТ НЕ СОВПАЛ: 1» вместе с
# `RC=0`. Причина была в записи лога через пайп (`... | tee`): `$?` брался от
# `tee`, а не от проверки — то есть ровно та ошибка «без pipefail», которую
# проект ловит в чужом коде.
#
# Теперь при `RC=0` тело лога дополнительно сканируется на маркеры провала.
# Маркеры подобраны так, чтобы НЕ давать ложных срабатываний: таймаут
# решателя, слово «error» в логе атаки и намеренный `[FAIL]` в canfail-пробе
# сюда не входят.
FAIL_MARKERS = (
    (re.compile(r"АТТЕСТАТ НЕ СОВПАЛ"), "аттестат не совпал"),
    (re.compile(r"НЕ СОВПАЛО с ожиданием:\s*[1-9]"), "несовпавших проверок > 0"),
    (re.compile(r"\[РАСХОЖДЕНИЕ\] исходники"), "расхождение отпечатка исходников"),
    (re.compile(r"^\s*error:\s", re.M), "ошибка компилятора"),
    (re.compile(r"failed;\s*[1-9]"), "провалившихся тестов > 0"),
    (re.compile(r"panics?:\s*[1-9]"), "паник > 0"),
    (re.compile(r"ЛОЖНЫХ СРАБАТЫВАНИЙ:\s*[1-9]"), "ложных срабатываний > 0"),
)


def main() -> int:
    if not EV.is_dir():
        print(f"[!] нет каталога {EV}")
        return 1

    logs = sorted(EV.glob("*.log"))
    if not logs:
        print("[!] в docs/evidence/ нет .log файлов")
        return 1

    problems: list[str] = []
    manual: list[str] = []
    checked = 0
    for p in logs:
        name = p.name
        text = p.read_text(encoding="utf-8", errors="replace")
        checked += 1

        # Финальный код возврата: последняя строка вида RC=<n>
        codes = re.findall(r"^RC=(\d+)\s*$", text, re.M)
        if not codes:
            problems.append(f"{name}: НЕТ финальной строки RC=<n> "
                            f"(лог неполный или снят вручную)")
            continue

        # 🔴 ДЕФЕКТ #81: лог обязан быть ОДНИМ прогоном. Если в файл писали два
        # процесса (или он дописан), внутри окажутся ДВА заголовка и результаты
        # двух прогонов — тогда «финальный RC» относится не к тем данным, а
        # строка вида «коммит совпал» встречается дважды с разными хешами.
        # Именно такой файл наблюдался у slsa_check.log.
        n_head = text.count("=== KERN EVIDENCE:")
        n_date = text.count("=== дата:")
        n_rc = len(codes)
        if n_head == 0:
            # Лог снят ВРУЧНУЮ (не сборщиком): заголовка нет по определению.
            # Инвариант для него — ровно ОДНА строка RC, иначе это дописывание.
            if n_rc != 1:
                problems.append(f"{name}: ручной лог содержит {n_rc} строк RC "
                                f"(похоже на дописывание)")
            else:
                manual.append(name)
            continue
        if n_head != 1 or n_date != 1 or n_rc != 1:
            problems.append(
                f"{name}: лог НЕ является одним прогоном "
                f"(заголовков {n_head}, дат {n_date}, строк RC {n_rc}) — "
                f"похоже на параллельную запись или дописывание")
            continue

        rc = codes[-1]

        if name in INTENTIONAL:
            pat, want, why = INTENTIONAL[name]
            m = re.search(pat, text)
            if not m:
                problems.append(f"{name}: не найден инвариант ({why})")
            elif int(m.group(1)) != want:
                problems.append(f"{name}: {why} — найдено {m.group(1)}")
            continue

        if rc != "0":
            # подсказать первую явную ошибку
            hint = ""
            for line in text.splitlines():
                if re.search(r"error:|ОШИБКА|ПРОВАЛ|failure", line):
                    hint = f"  первая ошибка: {line.strip()[:90]}"
                    break
            problems.append(f"{name}: RC={rc}{chr(10)}{hint}" if hint
                            else f"{name}: RC={rc}")
            continue

        # Второй эшелон (#77): RC=0, но в теле есть маркер провала.
        for pat, why in FAIL_MARKERS:
            m = pat.search(text)
            if m:
                line = text[:m.start()].count("\n") + 1
                problems.append(f"{name}: RC=0, но в теле провал ({why}) "
                                f"— строка {line}: {m.group(0)[:60]!r}")
                break

    print(f"СВИДЕТЕЛЬСТВА: проверено {checked} логов в docs/evidence/")
    if problems:
        print("НАРУШЕНИЯ:")
        for pr in problems:
            print(f"  - {pr}")
        print("\nИНВАРИАНТ: каждый опубликованный лог обязан заканчиваться RC=0")
        return 1
    print("ВСЕ ЧИСТЫЕ: ни одного лога с RC!=0; canfail.log — 0 вакуумных")
    if manual:
        print(f"  (сняты вручную, без заголовка сборщика: {len(manual)} — "
              f"{', '.join(manual)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
