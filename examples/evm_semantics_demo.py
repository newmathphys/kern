# ДЕФЕКТ #342 (шаг N12): ФРОНТЕНД `@kern:lang evm`.
#
# До этой директивы запись `evm` в `VALUE_SEMANTICS` была МЁРТВОЙ: `lang="evm"`
# не выставлялся ни одним путём разбора, поэтому реальный EVM-код через неё не
# проходил ни разу. Теперь директива в файле переопределяет расширение.
#
# Семантика Yellow Paper: `DIV`/`SDIV` усекают к нулю.
#
# ГРАНИЦА, НАЗВАННАЯ ЧЕСТНО: `SDIV(MIN, -1) = MIN` (оборачивание) здесь НЕ
# проверяется. В Int-модели границы типа нет (математические целые дают
# `2147483648`), а BV-путь упирается в покрытие пруф-чекера: Z3 доказывает, но
# наш чекер вывод в QF_BV не разбирает (класс #118). Это отдельная работа, а не
# «почти сделано» — см. `examples/evm_semantics_bv.c`, где виден честный SKIP.
# @kern:lang evm


# @kern:requires a == -7 and b == 2
# @kern:ensures result == -3
def evm_sdiv_truncates(a: int, b: int) -> int:
    """Усечение к НУЛЮ (не floor): (-7) / 2 == -3 в EVM, а floor дал бы -4."""
    return a // b


# @kern:requires a == 7 and b == 2
# @kern:ensures result == 3
def evm_div_positive(a: int, b: int) -> int:
    """Обычный случай: 7 / 2 == 3."""
    return a // b


# ГРАНИЦА, НАЗВАННАЯ ЧЕСТНО (найдено при проверке): КОНТРОЛЬНАЯ функция с
# floor-контрактом здесь НЕ ставится. Причина измерена: подтверждение
# контрпримера исполняет файл ЖИВЫМ Python (`a // b` = floor = -4), а проверка
# идёт с EVM-семантикой (trunc = -3) — вердикт получает метку «ЛОЖНАЯ ТРЕВОГА».
# То есть для `@kern:lang evm` в `.py`-файле рантайм-подтверждение БЕССМЫСЛЕННО:
# исполняется другой язык. Невакуумность этой проверки обеспечивает can-fail
# кейс `evm-lang` (диверсия убирает директиву), а не контроль в фикстуре.
