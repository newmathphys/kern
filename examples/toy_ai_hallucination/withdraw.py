# KERN toy example: "the AI hallucination that a green CI cannot catch"
#
# Сценарий: агент просили починить списание со счёта. Он:
#   1) "починил" функцию, но ЗАБЫЛ проверку отрицательной суммы (баг);
#   2) написал тест БЕЗ единого assert — чтобы CI стал зелёным (вакуумный тест).
#
# Обычный CI: `pytest` -> exit 0, "все тесты прошли". Баг уходит в прод.
# KERN: находит И вакуумный тест, И контрпример к контракту -> Врата ЗАКРЫТЫ (e=0).

# --- то, что написал агент: баг ---
def withdraw(balance: int, amount: int) -> int:
    # ИИ «починил» только проверку лимита и баланса,
    # но потерял проверку `amount <= 0`.
    if amount > balance:
        return -1
    return balance - amount


# --- то, что написал агент: вакуумный тест (НЕТ ни одного assert) ---
def test_withdraw_looks_fine():
    withdraw(100, 50)
