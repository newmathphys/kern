/* @kern:expect-violations — ДЕМО-ФИКСТУРА: функция `b64_tail_store_buggy`
 * НАМЕРЕННО нарушает контракт (это и есть моделируемый дефект), поэтому
 * pre-commit её пропускает. Парная `b64_tail_store_fixed` контракт держит. */

/* МОДЕЛЬ (не копия кода): арифметика хвоста SIMD-декодера Base64.
 *
 * Это НЕ воспроизведение какого-либо конкретного CVE и не утверждение о его
 * существовании — это минимальная модель класса «0 − 1 = −1 в длине хвоста,
 * из которой рождается маска «записать всё»». Ровно тот же механизм, что в
 * `TheAlgorithms/Rust#1075` (n − i без гарда) и в наших находках по `Ord`.
 *
 * Геометрия, которую моделируем (числа взяты из публичного описания
 * 65-символьного входа 64×'A' + '='):
 *   вход 65 символов -> 16 полных 4-символьных блоков = 48 выходных байт,
 *   остаток tail = 1 (одиночный паддинг), выходной буфер выделен на 50 байт.
 *   Остаточная длина считается как tail - 1 -> 0 - 1 -> underflow в -1,
 *   а из -1 генератор маски делает «все единицы»: 64 байта записи со
 *   смещения 48 при буфере 50 -> 62 байта за концом.
 *
 * Контракт ниже — это и есть инвариант, который должен держаться всегда:
 *      write_offset + write_bytes <= dst_len
 * KERN проверяет его на всех входах, а не на тех, что попали в тесты.
 */

/* Сколько байт SIMD-декодер собирается записать по маске, выведенной из
 * остаточной длины. Модель: маска накрывает ровно `len` байт, а при
 * отрицательной длине — весь 64-байтный регистр.
 * Честные ограничения модели: границы по регистрам не учитываются,
 * последовательность инструкций не моделируется — только счётчики длин. */

// @kern:requires in_len % 4 == 1 and 65 <= in_len and in_len <= 1024
// @kern:ensures  result >= 0
int b64_tail_remainder_buggy(int in_len) {
    int off = (in_len / 4) * 3;        /* 65 -> 48: записанные полные блоки */
    int decoded = (in_len * 3) / 4;    /* 65 -> 48: всего байт по формуле */
    int tail_out = decoded - off;      /* 65 -> 0: хвост декодируется в ноль */
    return tail_out - 1;               /* 0 - 1 = -1: underflow в длине */
}

/* Контракт, который ЛОМАЕТСЯ: длина хвоста обязана быть неотрицательной.
 * Эта длина уходит в генератор маски: отрицательное значение даёт «все
 * единицы», то есть 64 байта записи. Геометрия 65-байтного входа:
 *   off = (65/4)*3 = 48 записанных байт, decoded = (65*3)/4 = 48,
 *   tail_out = 0, return 0 - 1 = -1  ->  запись 64 байт со смещения 48
 *   в буфер на 50 байт  ->  62 байта за концом.
 * KERN предъявляет это как контрпример, без фаззинга и прогрева JIT. */

/* Исправление: остаток не бывает отрицательным. Ноль остаётся нулём,
 * единица (одиночный паддинг) даёт ноль, и только 2/3 дают 1/2. */
// @kern:requires 1 <= in_len and in_len <= 1024
// @kern:ensures  result >= 0 and result <= 2
int b64_tail_remainder_fixed(int in_len) {
    int off = (in_len / 4) * 3;
    int decoded = (in_len * 3) / 4;
    int tail_out = decoded - off;
    if (tail_out == 0) return 0;
    return tail_out - 1;
}
