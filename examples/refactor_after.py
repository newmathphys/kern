"""Фикстура KERN для `--diff-equiv` (УЛУЧШЕНИЕ №3): исходник ПОСЛЕ «рефакторинга».

ВНИМАНИЕ: расхождение НАМЕРЕННОЕ — знак операции перепутан (`+` вместо `-`).
Такая пара обязана дать `[DIVERGED]` с контрпримером, и цель `make diff-equiv`
падает, если этого не произошло. Фикстура нужна именно как «плохой» пример:
доказательство эквивалентности бесполезно, если оно не отличает плохое от
хорошего.
"""


def charge(balance: int, amount: int) -> int:
    """«Рефакторинг» с ошибкой: УВЕЛИЧИВАЕТ баланс вместо списания."""
    return balance + amount
