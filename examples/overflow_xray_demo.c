/*
 * ДЕМОНСТРАЦИЯ: `--xray` находит переполнение ВНУТРИ выражения.
 *
 * ЗАЧЕМ ЭТОТ ФАЙЛ. Свойство `no-overflow` требует, чтобы КАЖДАЯ
 * арифметическая операция оставалась в границах своего типа. До дефекта #367
 * `--xray` для C проверял только деление на ноль, границы массива, РАЗМЕР
 * АЛЛОКАЦИИ и ветвления — детектора переполнения ОБЫЧНОГО выражения не было.
 * ИЗМЕРЕНО на официальной категории SV-COMP `signedintegeroverflow-regression`:
 * поймано 0 из 10 unsafe. Этот файл — минимальное воспроизведение той причины.
 *
 * ПОЧЕМУ ЭТО НЕ ЛОВИТСЯ ПРОВЕРКОЙ ВОЗВРАТА. В `collapsing_sum` переполнение
 * происходит ВНУТРИ (`2147483647 + 1` = 2147483648), но ИТОГ снова попадает в
 * диапазон `int`. Контрактный путь проверяет итоговое значение возврата и
 * потому молчит: обязанность типа удовлетворена. Нарушено СВОЙСТВО
 * `no-overflow`, а не постусловие.
 *
 * ОЖИДАЕМЫЕ ВЕРДИКТЫ (проверяются гейтом `make xray-overflow-check`):
 *   collapsing_sum    -> [OVERFLOW PATH]  (переполнение внутри, итог в норме)
 *   guarded_sum       -> чисто            (гард снимает переполнение)
 *   promoted_sum      -> чисто            (целочисленное ПОВЫШЕНИЕ до int)
 *   wide_sum          -> чисто            (тип `long` — нет обязательства i32)
 *   wrapping_sum      -> чисто            (ЯВНОЕ оборачивание: законная семантика)
 *
 * ЭТИ ЧЕТЫРЕ «ЧИСТО» — НЕ УКРАШЕНИЕ, А ЗАЩИТА ОТ ЛОЖНЫХ ОБВИНЕНИЙ: каждое из
 * них в первой версии детектора давало находку (дефект #368), и файл-эталон
 * SV-COMP объяснял причину в своих же комментариях.
 */

/* ПЕРЕПОЛНЕНИЕ ВНУТРИ: итог 2147483625 снова в диапазоне int, но операция
 * `2147483647 + 1` уже вышла за него -> UB. Именно это и должен найти рентген. */
int collapsing_sum(void)
{
    int x = (2147483647 + 1) - 23;
    return x;
}

/* ГАРД: предел вынесен в константу, и сумма заведомо влезает. */
int guarded_sum(int a)
{
    if (a > 1000000)
    {
        return -1;
    }
    return a + 1000000;
}

/* ЦЕЛОЧИСЛЕННОЕ ПОВЫШЕНИЕ (C11 6.3.1.1): операнды `short` повышаются до `int`,
 * поэтому `a + a` в 16 битах НЕ переполняется. Обвинять нельзя. */
int promoted_sum(short a)
{
    int r = a + a;
    return r;
}

/* ШИРОКИЙ ТИП: `long` вмещает сумму, обязательства `i32` здесь нет. */
long wide_sum(long a)
{
    return a + 2000000000L;
}

/* ЯВНОЕ ОБОРАЧИВАНИЕ — ЗАКОННАЯ семантика: переполнение здесь задумано. */
unsigned int wrapping_sum(unsigned int a)
{
    unsigned int r = a + 1u;
    return r;
}
