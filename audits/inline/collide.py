"""ШАГ 1, ТЕСТ 3 (КОЛЛИЗИЯ ИМЁН) — ПРАВИЛО 1, главный тест звучимости.

`extra` внутри `helper` — СВОБОДНАЯ переменная (в Python это NameError). Если
инлайнинг наследует окружение вызывающего, `extra` свяжется с локальной
`extra = 5` из `caller`, и контракт ЛОЖНО докажется.

ОБЯЗАНО: НЕ `[PASS]`. Допустимо `[FAIL]` с контрпримером на префиксованном
символе — это и есть доказательство, что гигиена имён работает.
"""


def helper(x: int) -> int:
    return x + extra


# @kern:requires n > 0
# @kern:ensures result == n + 5
def caller(n: int) -> int:
    extra = 5
    return helper(n)
