/* C-like БАГОВАННЫЙ вариант для `--diff-equiv` (дефект #361).
 *
 * Настоящая ошибка: при `v > hi` возвращается `hi + 1`, то есть кламп
 * «перелетает» границу на единицу. Сравнение с исправленным обязано дать
 * `DIVERGED` и ТОЧНЫЙ контрпример (измерено: `hi = 0, v = 1`). */
int clamp_hi(int v, int hi) {
    if (v > hi) return hi + 1;
    return v;
}
