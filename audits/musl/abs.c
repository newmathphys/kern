/* ТЕНЬ-КОНТРАКТ на РЕАЛЬНУЮ функцию musl libc:
 *   src/stdlib/abs.c:   int abs(int a) { return a>0 ? a : -a; }
 *   (проверено в исходнике: git.musl-libc.org/cgit/musl/plain/src/stdlib/abs.c)
 *
 * ЗАЧЕМ: `abs` — одна из самых вызываемых функций стандартной библиотеки, и её
 * контракт («результат неотрицателен») обязан держаться на всём домене. Класси-
 * ческая ошибка — забыть отрицательную ветвь (`return a;`), и тогда на первом
 * же отрицательном входе инвариант ломается.
 *
 * ТЕОРИЯ: QF_LIA (Int) — арифметика линейная, поэтому вывод Z3 покрывается
 * пруф-чекером целиком (`[PROOF VERIFIED]`, holes: 0).
 *
 * ЧЕСТНАЯ ГРАНИЦА: `abs(INT_MIN)` — неопределённое поведение (|INT_MIN| не
 * представим в i32), поэтому домен ограничен `a > -2147483648`. Это ровно то
 * условие, которое обязан обеспечить вызывающий; без него KERN справедливо
 * сообщил бы ПЕРЕПОЛНЕНИЕ, а не «доказано».
 *
 * ТРАНСКРИПЦИЯ (честно): тернарный оператор C в поддерживаемом подмножестве
 * записывается через if/else — семантика та же.
 */

/// @kern:requires a > -2147483648
/// @kern:ensures  result >= 0
int kern_abs(int a) {
    if (a < 0) return -a; else return a;
}

/* КОНТРОЛЬ (мутация): убрана отрицательная ветвь — «abs» возвращает вход как
 * есть. Тот же контракт обязан опровергнуть её на первом же отрицательном. */
/// @kern:requires a > -2147483648
/// @kern:ensures  result >= 0
int kern_absBroken(int a) {
    return a;
}
