/* Реальная возможность KERN: ЯВНЫЙ BV-режим ловит переполнение `a * b`.
 *
 * `a * b` двух переменных НЕЛИНЕЙНО в Int-теории (QF_LIA его не решает),
 * поэтому без директивы функция ушла бы BV-кандидатом. Директива
 * `@kern:bitvec32` ЯВНО включает теорию битовых векторов — и тогда
 * переполнение ловится с контрпримером, а не пропускается.
 *
 * ИЗМЕРЕНО: `[BV] mul_bv (стр. 4): теория битовых векторов (_ BitVec 32,
 * знаковый)` + `[FAIL] КОНТРАКТ НАРУШЕН`. */
// @kern:bitvec32
// @kern:requires a > 0 and b > 0
// @kern:ensures result > 0
int mul_bv(int a, int b) {
    return a * b;
}
