"""Анатомия одной функции: ЛИНЕЙНАЯ функция с настоящим дефектом.

`--diff-equiv` сравнивает в Int-теории, поэтому для сквозной цепочки из 6
режимов берётся ЛИНЕЙНОЕ тело (`a // b`), а не `a * b`: тогда все режимы
проходят в QF_LIA от начала до конца без пропусков.

Дефект настоящий: делитель не защищён, поэтому `b = 0` даёт деление на ноль.
"""

# @kern:ensures result == a // b
def div_bad(a: int, b: int) -> int:
    return a // b
