/* CWE-680 Integer Overflow to Buffer Size (NIST Juliet-style `bad` twin).
 *
 * Настоящий дефект: размер буфера `n * size` вычисляется в знаковом int и
 * переполняется, после чего аллокация получает ОТРИЦАТЕЛЬНЫЙ (т. е. огромный
 * беззнаковый) размер — классический путь к переполнению кучи.
 *
 * ЧЕСТНО О ПЕРЕСЕЧЕНИИ С CWE-190: обязательство типа здесь то же (диапазон
 * типа); отличие в КОНТЕКСТЕ — результат уходит в размер аллокации. Классы
 * разделены так, как это делает сам NIST SARD (разные CWE на одну арифметику
 * в разных контекстах), и это названо, а не спрятано. */
// @kern:requires n > 0 and size > 0
// @kern:ensures result > 0
int buffer_size(int n, int size) {
    return n * size;
}
