/* ТЕНЕВОЙ КОНТРАКТ для реального дефекта в `TheAlgorithms/C` `math/lcm.c`
 * (PR #1596): там написано `(a * b) / gcd(a, b)`. Вызов `gcd` вне подмножества
 * KERN, поэтому проверяется АРИФМЕТИЧЕСКОЕ ЯДРО — выражение `a * b`, дословно
 * взятое из апстрима.
 *
 * Почему это дефект, а не «наша формулировка»: `lcm(a, b)` может быть МАЛ и
 * влезать в `int`, но промежуточное `a * b` переполняется раньше деления.
 * Измерено `gcc -fsanitize=undefined`: при `a = 50000, b = 50000` истинный
 * НОК равен `50000`, а программа печатает `-35899` (UB: signed integer overflow).
 *
 * Ожидание: `[FAIL]` с контрпримером (обязанность безопасности НЕ выполнена).
 */
// @kern:requires a >= 0 and b >= 0
// @kern:ensures result >= a
int lcm_numerator(int a, int b) {
    return a * b;
}
